export function normalizeStationName(value: string | undefined | null): string {
  if (!value) {
    return '';
  }

  return value
    .trim()
    .replace(/\s+/g, '')
    .replace(/\([^)]*\)/g, '')
    .replace(/역$/, '')
    .toLowerCase();
}

export function normalizeLineName(value: string | undefined | null): string {
  if (!value) {
    return '';
  }

  return value.trim().replace(/\s+/g, '').toLowerCase();
}

export function findSeoulMetroLineMeta(input: string | number | undefined | null) {
  if (typeof input === 'number') {
    return SEOUL_METRO_LINE_META.find(line => line.subwayLineId === input) ?? null;
  }

  const normalized = normalizeLineName(input);

  return (
    SEOUL_METRO_LINE_META.find(line => {
      if (normalizeLineName(line.code) === normalized) {
        return true;
      }

      if (normalizeLineName(line.nameKo) === normalized) {
        return true;
      }

      if (normalizeLineName(line.nameEn) === normalized) {
        return true;
      }

      return line.aliases?.some(alias => normalizeLineName(alias) === normalized) ?? false;
    }) ?? null
  );
}

function getStationMatchNames(station: SeoulMetroSvgStationDef) {
  return [station.n, ...(station.aliases ?? []), ...(STATION_NAME_ALIASES[station.n] ?? [])];
}

